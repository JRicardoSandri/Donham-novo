function format(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '');
}

export function deviceLanguage() {
  const locale = Platform.OS === 'ios'
    ? NativeModules.SettingsManager?.settings?.AppleLocale
      || NativeModules.SettingsManager?.settings?.AppleLanguages?.[0]
    : NativeModules.I18nManager?.localeIdentifier;
  return normalizeLanguage(locale);
}

export function normalizeLanguage(language) {
  const value = String(language || '').replace('_', '-').toLowerCase();
  if (value.startsWith('pt')) return 'pt-BR';
  if (value.startsWith('es')) return 'es';
  if (value.startsWith('en')) return 'en';
  return 'pt-BR';
}

export function activeLanguage(settings = {}) {
  return settings.languageMode === 'manual'
    ? normalizeLanguage(settings.language)
    : deviceLanguage();
}

export function t(key, language = 'pt-BR', values = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  const template = BASE_TRANSLATIONS[normalizedLanguage]?.[key]
    || BASE_TRANSLATIONS['pt-BR'][key]
    || key;
  return format(template, values);
}

export function tr(text, language = 'pt-BR', values = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  if (normalizedLanguage === 'pt-BR') return format(text, values);
  const template = TEXT_TRANSLATIONS[normalizedLanguage]?.[text]
    || TEXT_TRANSLATIONS.en?.[text]
    || text;
  return format(template, values);
}

export function gameTerm(value, language = 'pt-BR') {
  const normalizedLanguage = normalizeLanguage(language);
  if (value === null || value === undefined) return '';
  const text = String(value);
  if (normalizedLanguage === 'pt-BR') return text;
  return TERM_TRANSLATIONS[normalizedLanguage]?.[text]
    || TERM_TRANSLATIONS.en?.[text]
    || tr(text, normalizedLanguage);
}

export function featureText(value, language = 'pt-BR') {
  const normalizedLanguage = normalizeLanguage(language);
  const text = String(value || '');
  if (!text || normalizedLanguage === 'pt-BR') return text;

  const translated = FEATURE_TRANSLATIONS[normalizedLanguage]?.[text]
    || FEATURE_TRANSLATIONS.en?.[text];
  if (translated) return translated;

  return text
    .split(';')
    .map((part) => {
      const trimmed = part.trim();
      return FEATURE_TRANSLATIONS[normalizedLanguage]?.[trimmed]
        || FEATURE_TRANSLATIONS.en?.[trimmed]
        || gameTerm(trimmed, normalizedLanguage);
    })
    .join('; ');
}

export function spellName(spell, language = 'pt-BR') {
  if (!spell) return '';
  const normalizedLanguage = normalizeLanguage(language);
  if (normalizedLanguage === 'pt-BR') return spell.name;
  return SPELL_NAMES[normalizedLanguage]?.[spell.id]
    || SPELL_NAMES.en?.[spell.id]
    || spell.name;
}

export function spellSummary(spell, language = 'pt-BR') {
  if (!spell) return '';
  const normalizedLanguage = normalizeLanguage(language);
  if (normalizedLanguage === 'pt-BR') return spell.summary;
  return t(spell.circle === 0 ? 'spellSummaryCantrip' : 'spellSummaryLeveled', normalizedLanguage);
}

export function spellCircleLabel(circle, language = 'pt-BR') {
  const normalizedLanguage = normalizeLanguage(language);
  if (circle === 'Todos') return tr('Todos', normalizedLanguage);
  if (Number(circle) === 0) return tr('Truques', normalizedLanguage);
  if (normalizedLanguage === 'en') return `Level ${circle}`;
  if (normalizedLanguage === 'es') return `Nivel ${circle}`;
  return `${circle}º`;
}

export function resourceName(name, language = 'pt-BR') {
  const normalizedLanguage = normalizeLanguage(language);
  if (normalizedLanguage === 'pt-BR') return name;
  return String(name || '')
    .split('·')
    .map((part) => gameTerm(part.trim(), normalizedLanguage))
    .join(' · ');
}

