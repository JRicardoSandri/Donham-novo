export function criticalErrorTableById(tableId) {
  return CRITICAL_ERROR_TABLES.find((table) => table.id === tableId) || CRITICAL_ERROR_TABLES[0];
}

export function rollCriticalError(tableId) {
  const table = criticalErrorTableById(tableId);
  const roll = Math.floor(Math.random() * 100) + 1;
  const entry = table.effects.find((effect) => roll >= effect.min && roll <= effect.max) || table.effects[0];
  return {
    tableId: table.id,
    tableName: table.name,
    die: table.die,
    roll,
    range: entry.range,
    chance: entry.chance,
    severity: entry.severity,
    effect: entry.effect,
  };
}
